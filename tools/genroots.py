#!/usr/bin/env python3
"""Generate kernel/roots.h: a trust store of well-known root CA certs (DER)."""
import subprocess, re, sys
BUNDLE='/etc/ssl/certs/ca-certificates.crt'
WANT=[("GTS Root R1","Google Trust Services"),
      ("GTS Root R4","Google Trust Services"),
      ("ISRG Root X1","Internet Security Research"),
      ("DigiCert Global Root G2","DigiCert"),
      ("GlobalSign Root CA - R3","GlobalSign"),
      ("GlobalSign ECC Root CA - R4","GlobalSign")]
data=open(BUNDLE).read()
certs=re.findall(r'-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----', data, re.S)
picked=[]
for cn,org in WANT:
    for c in certs:
        subj=subprocess.run(['openssl','x509','-noout','-subject'],input=c,capture_output=True,text=True).stdout
        if cn in subj and org in subj:
            der=subprocess.run(['openssl','x509','-outform','DER'],input=c,capture_output=True,text=True.__class__==str and False or True).stdout if False else \
                subprocess.run(['openssl','x509','-outform','DER'],input=c.encode(),capture_output=True).stdout
            picked.append((cn,der)); break
    else:
        print("WARN missing",cn,file=sys.stderr)
with open('kernel/roots.h','w') as f:
    f.write("/* Auto-generated by tools/genroots.py - trusted root CAs (DER). Do not edit. */\n")
    f.write("#ifndef AXIS_ROOTS_H\n#define AXIS_ROOTS_H\n#include <stdint.h>\n\n")
    for i,(cn,der) in enumerate(picked):
        f.write(f"/* {cn} ({len(der)} bytes) */\n")
        f.write(f"static const uint8_t root_{i}[] = {{\n")
        for j in range(0,len(der),16):
            f.write("  "+",".join("0x%02x"%b for b in der[j:j+16])+",\n")
        f.write("};\n")
    f.write("\nstatic const struct { const uint8_t *der; uint32_t len; } axis_roots[] = {\n")
    for i,(cn,der) in enumerate(picked):
        f.write(f"  {{ root_{i}, {len(der)} }},\n")
    f.write("};\n")
    f.write(f"#define AXIS_ROOTS_N {len(picked)}\n")
    f.write("#endif\n")
print(f"wrote kernel/roots.h with {len(picked)} roots")
